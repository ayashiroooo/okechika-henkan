// 変換する関数
function convertText() {

    // 入力された文章を取得
    const input = document.getElementById("inputText").value;

    // 1文字ずつ変換
    const result = [...input].map(function(char) {

        // 対応表に文字が存在するなら変換
        if (mapping[char]) {
            return mapping[char];
        }

        // 対応表にない文字はそのまま
        return char;

    }).join("");

    // 結果を表示
    document.getElementById("outputText").value = result;
}
